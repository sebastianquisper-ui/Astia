import { describe, expect, it } from 'vitest'
import { crearRepoLocal } from './repoLocal'
import type { Config, Meta, Movimiento } from './tipos'

const nuevo = () => crearRepoLocal({ guardar: false })
const mov = (extra: Partial<Movimiento> = {}) => ({ tipo: 'gasto' as const, categoria: 'Almuerzos', monto: 12.5, fecha: '2026-10-15', medio: 'digital' as const, ...extra })
const config = (r: ReturnType<typeof nuevo>) => new Promise<Config>((ok) => { const f = r.escucharConfig((c) => { ok(c); queueMicrotask(f) }) })
const metas = (r: ReturnType<typeof nuevo>) => new Promise<Meta[]>((ok) => { const f = r.escucharMetas((m) => { ok(m); queueMicrotask(f) }) })

describe('finanzas en el teléfono (misma lógica que Firestore)', () => {
  it('un gasto resta del saldo de su billetera y un ingreso suma', async () => {
    const r = nuevo()
    r.crearMovimiento(mov({ tipo: 'ingreso', categoria: 'Sueldo', monto: 100 }))
    r.crearMovimiento(mov({ monto: 12.5 }))
    r.crearMovimiento(mov({ monto: 5, medio: 'efectivo' }))
    expect((await config(r)).saldosCent).toEqual({ digital: 8750, efectivo: -500 })
  })
  it('rechaza lo inválido con un mensaje claro', () => {
    const r = nuevo()
    expect(() => r.crearMovimiento(mov({ monto: 0 }))).toThrow('monto mayor que 0')
    expect(() => r.crearMovimiento(mov({ categoria: ' ' }))).toThrow('categoría')
    expect(() => r.crearMovimiento(mov({ fecha: '2026-13-40' }))).toThrow('Fecha inválida')
  })
  it('editar un movimiento corrige los saldos (también si cambia de billetera)', async () => {
    const r = nuevo()
    const { id } = r.crearMovimiento(mov({ monto: 10 }))
    const [anterior] = await r.todosLosMovimientos()
    expect(anterior.id).toBe(id)
    await r.actualizarMovimiento(anterior, { monto: 30, medio: 'efectivo' })
    expect((await config(r)).saldosCent).toEqual({ digital: 0, efectivo: -3000 })
  })
  it('una transferencia crea dos patas y mueve plata entre billeteras', async () => {
    const r = nuevo()
    r.crearTransferencia({ origen: 'digital', destino: 'efectivo', monto: 50, fecha: '2026-10-15' })
    const movs = await r.todosLosMovimientos()
    expect(movs).toHaveLength(2)
    expect(movs[0].transferId).toBe(movs[1].transferId)
    expect((await config(r)).saldosCent).toEqual({ digital: -5000, efectivo: 5000 })
    expect(() => r.crearTransferencia({ origen: 'digital', destino: 'digital', monto: 5, fecha: '2026-10-15' })).toThrow('dos medios distintos')
  })
  it('borrar una transferencia borra las dos patas y se puede deshacer', async () => {
    const r = nuevo()
    r.crearTransferencia({ origen: 'digital', destino: 'efectivo', monto: 50, fecha: '2026-10-15' })
    const [una] = await r.todosLosMovimientos()
    const { borrados } = await r.eliminarMovimiento(una)
    expect(borrados).toHaveLength(2)
    expect(await r.todosLosMovimientos()).toHaveLength(0)
    expect((await config(r)).saldosCent).toEqual({ digital: 0, efectivo: 0 })
    await r.restaurarMovimientos(borrados)
    expect(await r.todosLosMovimientos()).toHaveLength(2)
    expect((await config(r)).saldosCent).toEqual({ digital: -5000, efectivo: 5000 })
  })
  it('las transferencias no se editan como un movimiento normal', async () => {
    const r = nuevo()
    r.crearTransferencia({ origen: 'digital', destino: 'efectivo', monto: 50, fecha: '2026-10-15' })
    const [una] = await r.todosLosMovimientos()
    expect(() => r.actualizarMovimiento(una, { monto: 5 })).toThrow('actualizarTransferencia')
    await r.actualizarTransferencia(una.transferId!, { monto: 20, fecha: '2026-10-16', nota: 'ajuste' })
    expect((await config(r)).saldosCent).toEqual({ digital: -2000, efectivo: 2000 })
  })
  it('escuchar por rango de fechas devuelve solo ese rango', async () => {
    const r = nuevo()
    r.crearMovimiento(mov({ fecha: '2026-10-01' }))
    r.crearMovimiento(mov({ fecha: '2026-11-01' }))
    expect(await r.movimientosEntre('2026-10-01', '2026-10-31')).toHaveLength(1)
  })
  it('recalcular saldos los reconstruye desde el historial', async () => {
    const r = nuevo()
    r.crearMovimiento(mov({ monto: 10 }))
    expect(await r.recalcularSaldos()).toEqual({ digital: -1000, efectivo: 0 })
  })
  it('presupuestos: se definen y con tope vacío se quitan', async () => {
    const r = nuevo()
    await r.definirPresupuesto('digital', 'Almuerzos', 200)
    expect((await config(r)).presupuestos.digital).toEqual({ Almuerzos: 200 })
    await r.definirPresupuesto('digital', 'Almuerzos', null)
    expect((await config(r)).presupuestos.digital).toEqual({})
    expect(() => r.definirPresupuesto('digital', 'Extras', -5)).toThrow('mayor que 0')
  })
  it('metas: aportar, retirar sin pasarse y borrar', async () => {
    const r = nuevo()
    r.crearMeta({ nombre: 'Laptop', objetivo: 3200, limite: '2027-05-28' })
    let [meta] = await metas(r)
    await r.aportarAMeta(meta, 850, '2026-10-15')
    ;[meta] = await metas(r)
    expect(meta.aportes).toHaveLength(1)
    expect(() => r.aportarAMeta(meta, -900, '2026-10-16')).toThrow('más de lo ahorrado')
    expect(() => r.aportarAMeta(meta, 0, '2026-10-16')).toThrow('distinto de 0')
    await r.aportarAMeta(meta, -50, '2026-10-16')
    ;[meta] = await metas(r)
    expect(meta.aportes.map((a) => a.monto)).toEqual([850, -50])
    await r.eliminarMeta(meta)
    expect(await metas(r)).toHaveLength(0)
    expect(() => r.crearMeta({ nombre: '', objetivo: 5 })).toThrow('nombre')
  })
  it('las metas no tocan los saldos de las billeteras', async () => {
    const r = nuevo()
    r.crearMeta({ nombre: 'Viaje', objetivo: 100 })
    const [meta] = await metas(r)
    await r.aportarAMeta(meta, 40, '2026-10-15')
    expect((await config(r)).saldosCent).toEqual({ digital: 0, efectivo: 0 })
  })
})
